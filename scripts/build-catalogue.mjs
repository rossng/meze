// Generates seed/mezes/*.sql from the authored catalogue entries in
// seed/catalogue/*.json. Run after editing an entry:  npm run catalogue
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'seed', 'catalogue');
const OUT = path.join(ROOT, 'seed', 'mezes');

const q = (v) => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const entries = [];
for (const f of (await fs.readdir(SRC)).filter((f) => f.endsWith('.json')).sort()) {
  entries.push(...JSON.parse(await fs.readFile(path.join(SRC, f), 'utf8')));
}

const seen = new Set();
for (const e of entries) {
  if (seen.has(e.id)) throw new Error(`duplicate id: ${e.id}`);
  seen.add(e.id);
  if (e.ing.length !== e.count) throw new Error(`${e.id}: ingredient_count ${e.count} but ${e.ing.length} rows`);
  if (!e.tags.some((t) => t.startsWith('temp:'))) throw new Error(`${e.id}: no temp tag`);
}

const byFile = new Map();
for (const e of entries) {
  if (!byFile.has(e.file)) byFile.set(e.file, []);
  byFile.get(e.file).push(e);
}

await fs.mkdir(OUT, { recursive: true });
for (const [file, group] of [...byFile].sort()) {
  const rows = group.map((e) =>
    `(${q(e.id)}, ${q(e.name)}, ${q(e.tr)},\n ${q(e.desc)},\n ${q(e.photo ?? null)}, ${q(e.photo ? e.photo.replace('.webp', '-thumb.webp') : null)}, ${q(e.credit ?? null)}, ${q(e.emoji)},\n ${q(e.recipe ?? null)}, ${q(e.recipeSource ?? null)}, ${e.prep}, ${e.count}, ${e.serves})`);
  const tags = group.map((e) => `-- ${e.id}\n` + e.tags.map((t) => `(${q(e.id)},${q(t)})`).join(',') + ',');
  const ing = group.map((e) => e.ing.map(([qty, unit, item, note], i) => `(${q(e.id)},${i + 1},${q(qty)},${q(unit)},${q(item)},${q(note)})`).join(',') + ',');

  const sql = [
    `-- Generated by scripts/build-catalogue.mjs from seed/catalogue/. Do not edit by hand.`,
    ``,
    `INSERT INTO mezes (id, name, name_tr, description, photo_url, photo_thumb_url, photo_credit, art_emoji, recipe_url, recipe_source, prep_minutes, ingredient_count, serves) VALUES`,
    rows.join(',\n\n') + '',
    `ON CONFLICT (id) DO UPDATE SET`,
    `  name = excluded.name, name_tr = excluded.name_tr, description = excluded.description,`,
    `  photo_url = excluded.photo_url, photo_thumb_url = excluded.photo_thumb_url, photo_credit = excluded.photo_credit,`,
    `  art_emoji = excluded.art_emoji, recipe_url = excluded.recipe_url, recipe_source = excluded.recipe_source,`,
    `  prep_minutes = excluded.prep_minutes, ingredient_count = excluded.ingredient_count, serves = excluded.serves;`,
    ``,
    `INSERT INTO meze_tags (meze_id, tag_id) VALUES`,
    tags.join('\n').replace(/,$/, ';'),
    ``,
    `INSERT INTO meze_ingredients (meze_id, sort, quantity, unit, item, note) VALUES`,
    ing.join('\n').replace(/,$/, ';'),
    ``,
  ].join('\n');
  await fs.writeFile(path.join(OUT, `${file}.sql`), sql);
  console.log(`${file}.sql: ${group.length} mezes`);
}
console.log(`${entries.length} entries total`);
